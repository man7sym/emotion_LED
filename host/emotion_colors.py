# ── 편의 함수 ──────────────────────────────────────────

def get_color(label: str) -> tuple[int, int, int]:
    """레이블 문자열 → RGB 튜플. 미등록 시 중립 회색 반환."""
    return EMOTION_COLORS.get(label, (180, 180, 180))


def get_hex(label: str) -> str:
    """레이블 → HEX 문자열 (#RRGGBB)."""
    r, g, b = get_color(label)
    return f"#{r:02X}{g:02X}{b:02X}"


def get_css_rgb(label: str) -> str:
    """레이블 → CSS rgb() 문자열."""
    r, g, b = get_color(label)
    return f"rgb({r}, {g}, {b})"


